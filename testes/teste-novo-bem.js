const { chromium } = require('/opt/node22/lib/node_modules/playwright');
const O = __dirname + '/frota-prints';
let falhas = 0; const ok = (c, m) => { console.log((c ? 'PASSOU ' : 'FALHOU ') + m); if (!c) falhas++; };
(async () => {
  const b = await chromium.launch(); const erros = [];
  const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, locale: 'pt-BR' });
  for (const k of ['patrimonio', 'cemiterio']) await ctx.route(`**/${k}/config-servidor.js`, (r) => r.fulfill({ contentType: 'text/javascript', body: `window.VP_SERVIDOR_${k.toUpperCase()} = { url: '', chavePublica: '', municipio: '' };` }));
  const p = await ctx.newPage(); p.on('pageerror', (e) => erros.push(e.message)); p.on('console', (m) => { if (m.type() === 'error') erros.push(m.text()); });
  const dlg = 'dialog.janela[open]';
  await p.goto('http://localhost:8765/'); await p.fill('#usuario', 'patrimonio'); await p.fill('#senha', '123456'); await p.click('button[type=submit]');
  await p.waitForFunction(() => window.VP_PRONTO === true, null, { timeout: 60000 });
  await p.evaluate(() => { location.hash = 'novo-bem/movel'; }); await p.waitForTimeout(500);
  ok((await p.inputValue('#form-novo [name=estado]')) === '8', 'estado padrão = Novo (8 na escala nova)');
  ok(await p.isVisible('.detalhes-bem') && !(await p.textContent('#form-novo')).includes('opcional'), 'detalhes aparecem abertos, sem "opcional"');
  await p.fill('#f-descricao', 'Notebook'); await p.waitForTimeout(200);
  ok((await p.textContent('#achado-nome')).includes('Já cadastrado'), 'nome igual ao existente: oferece puxar informações');
  await p.click('[data-usar-anterior]'); await p.waitForTimeout(200);
  ok((await p.inputValue('#f-classificacao')).length > 0 && (await p.textContent('#achado-classe')).includes('✓'), 'puxou a classificação: ' + await p.inputValue('#f-classificacao'));
  await p.fill('#form-novo [name=valor]', '4500,00'); await p.selectOption('#form-novo [name=unidadeId]', 'U1');
  await p.click('#form-novo button[type=submit]'); await p.waitForSelector(`${dlg} footer button:has-text("Fechar")`); await p.click(`${dlg} footer button:has-text("Fechar")`);
  ok(p.url().includes('#bem/'), 'bem incluído com nome do catálogo');
  // nome e classificação novos
  await p.evaluate(() => { location.hash = 'novo-bem/movel'; }); await p.waitForTimeout(500);
  await p.fill('#f-descricao', 'Drone de mapeamento (exemplo)'); await p.waitForTimeout(100);
  ok((await p.textContent('#achado-nome')).includes('Nome novo'), 'nome novo: avisa que entra no catálogo');
  await p.fill('#f-classificacao', 'Equipamentos de topografia'); await p.waitForTimeout(100);
  ok((await p.textContent('#achado-classe')).includes('Classificação nova'), 'classificação nova: avisa que será criada');
  await p.fill('#form-novo [name=valor]', '18900,00'); await p.selectOption('#form-novo [name=unidadeId]', 'U1');
  await p.click('#form-novo button[type=submit]'); await p.waitForTimeout(800);
  await p.waitForSelector(`${dlg} footer button:has-text("Fechar")`);
  const res = await p.textContent(dlg);
  ok(res.includes('Classificação nova') && res.includes('Produto novo'), 'resultado informa produto e classificação criados nos Cadastros');
  await p.click(`${dlg} footer button:has-text("Fechar")`);
  ok(await p.evaluate(() => VP.db.lista('produtos').some((x) => x.nome === 'Drone de mapeamento (exemplo)') && VP.db.lista('classificacoes').some((x) => x.nome === 'Equipamentos de topografia')), 'produto e classificação novos estão nos Cadastros');
  // nota fiscal
  await p.evaluate(() => { location.hash = 'novo-bem/movel'; }); await p.waitForTimeout(500);
  const antes = await p.evaluate(() => VP.db.lista('bens').length);
  await p.setInputFiles('[data-nfe]', require('path').resolve(__dirname, '..') + '/patrimonio/gestao/exemplos/nfe-exemplo.xml'); await p.waitForSelector(dlg);
  const corpo = await p.textContent(dlg);
  ok(corpo.includes('Nota 4567') && (await p.$$('.item-nf')).length === 3, 'nota lida: 3 itens');
  ok(corpo.includes('Mudou em relação ao cadastro anterior') && corpo.includes('Valor unitário'), 'item já cadastrado com valor diferente: pede conferência');
  ok(corpo.includes('Fornecedor ainda não cadastrado'), 'fornecedor novo avisado');
  await p.screenshot({ path: O + '/nota-fiscal.png' });
  const vazias = await p.$$eval('.item-nf [data-classe]', (els) => els.map((e, i) => (!e.value ? i : -1)).filter((i) => i >= 0));
  for (const i of vazias) await p.fill(`.item-nf[data-i="${i}"] [data-classe]`, 'Monitores');
  await p.click(`${dlg} footer button:has-text("Incluir bens")`); await p.waitForSelector(`${dlg} footer button:has-text("Fechar")`);
  const r2 = await p.textContent(dlg);
  const depois = await p.evaluate(() => VP.db.lista('bens').length);
  ok(depois - antes === 9, `9 bens criados (2 + 3 + 4): ${depois - antes}`);
  ok(await p.evaluate(() => VP.db.lista('bens').filter((b) => b.nf?.numero === '4567').every((b) => b.nf.chave && b.fornecedorId)), 'bens com número e chave da nota e fornecedor');
  ok(await p.evaluate(() => VP.db.lista('fornecedores').some((f) => f.documento === '11222333000181')), 'fornecedor da nota incluído nos Cadastros');
  console.log('   resultado:', r2.replace(/\s+/g, ' ').slice(0, 300));
  ok(erros.length === 0, 'sem erros ' + JSON.stringify(erros));
  console.log(falhas ? `${falhas} FALHA(S)` : 'TUDO PASSOU'); await b.close(); process.exit(falhas ? 1 : 0);
})();
