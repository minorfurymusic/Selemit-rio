// Testa o VitalPat Cemitério no MESMO navegador/endereço onde o Patrimônio já tem dados.
const fs = require('fs');
module.exports = async (b, ctxPat, S0, ok, erros) => {
  const URL = 'http://localhost:8765/cemiterio/app-campo/';
  const p = await ctxPat.newPage();
  p.on('pageerror', e => erros.push('cem: ' + e.message));
  await p.goto(URL); await p.waitForURL(/index\.html\?motivo=sem-acesso/);
  ok((await p.textContent('#erro')).includes('não tem acesso'), 'usuário patrimonio não entra no Cemitério');
  // Sair do patrimônio e entrar com o usuário do cemitério
  await p.goto('http://localhost:8765/patrimonio/app-campo/'); await p.waitForSelector('#sair');
  await p.click('#sair'); await p.waitForURL(/index\.html\?motivo=saiu/);
  ok(true, 'botão Sair volta para o login');
  await p.fill('#usuario', 'selemitério'); await p.fill('#senha', '123456'); await p.click('button[type=submit]');
  await p.waitForURL('http://localhost:8765/cemiterio/gestao/');
  ok(true, 'login selemitério abre a Gestão do Cemitério');
  await p.goto('http://localhost:8765/'); await p.waitForURL('http://localhost:8765/cemiterio/gestao/');
  ok(true, 'já logado: abrir o endereço principal vai direto à Gestão do Cemitério');
  await p.goto(URL); await p.waitForSelector('[data-ir]');
  await p.evaluate(() => navigator.serviceWorker.ready);
  ok((await p.$$('[data-ir]')).length === 5, 'cemitério: tela inicial com 5 opções (túmulo, ordens, aviso, registros, lixeira)');
  ok(await p.textContent('#titulo') === 'VitalPat Cemitério', 'cemitério: título próprio');
  ok((await p.textContent('#qtd-aguardando')) === '0', 'cemitério não enxerga os registros do Patrimônio');
  await p.screenshot({ path: S0 + '/prints/cemiterio/1-inicio-celular.png', fullPage: true });
  await p.goto(URL + '#tumulo'); await p.fill('#codigo', 'q01-a1-2'); await p.dispatchEvent('#codigo', 'change');
  for (const [v, n] of [['v1','3'],['v2','4'],['v3','2'],['v4','1'],['v5','Não']]) await p.click(`#${v} button[data-valor="${n}"]`);
  await p.setInputFiles('#fotos', require('path').resolve(__dirname, '..') + '/cemiterio/app-campo/icones/icone-192.png');
  await p.waitForSelector('#previa-fotos img');
  await p.screenshot({ path: S0 + '/prints/cemiterio/2-vistoria-tumulo.png', fullPage: true });
  await p.click('#salvar'); await p.waitForTimeout(400);
  await p.goto(URL + '#registros'); await p.waitForSelector('.lista');
  const [dl] = await Promise.all([p.waitForEvent('download'), p.click('#csv')]);
  const csv = fs.readFileSync(await dl.path(), 'utf8');
  ok(dl.suggestedFilename().startsWith('vitalpat-cemiterio-registros-'), 'cemitério: nome do arquivo próprio');
  ok(csv.split('\r\n').length === 2 && csv.includes('Q01-A1-2'), 'cemitério: planilha com 1 vistoria');
  await p.screenshot({ path: S0 + '/prints/cemiterio/3-registros.png', fullPage: true });
  const bancos = await p.evaluate(async () => (await indexedDB.databases()).map(d => d.name).sort());
  ok(bancos.includes('vitalpat-cemiterio') && bancos.includes('vitalpat-patrimonio') && bancos.every((x) => ['vitalpat-cemiterio', 'vitalpat-cemiterio-gestao', 'vitalpat-patrimonio', 'vitalpat-patrimonio-gestao'].includes(x)), 'cada sistema com seu armazenamento: ' + JSON.stringify(bancos));
  const caches_ = await p.evaluate(async () => (await caches.keys()).sort());
  ok(caches_.length === 2 && caches_.some(c => c.startsWith('vitalpat-patrimonio-')), 'cache do Patrimônio continua lá depois de abrir o Cemitério: ' + JSON.stringify(caches_));
  // Sem internet: os dois abrem
  await ctxPat.setOffline(true);
  await p.goto(URL + '#inicio'); await p.waitForSelector('#qtd-aguardando');
  ok((await p.textContent('#qtd-aguardando')) === '1', 'cemitério sem internet: 1 registro no aparelho');
  await ctxPat.setOffline(false);
  const nPat = await p.evaluate(() => new Promise(r => { const q = indexedDB.open('vitalpat-patrimonio'); q.onsuccess = () => { const g = q.result.transaction('registros').objectStore('registros').getAll(); g.onsuccess = () => r(g.result.length); }; }));
  ok(nPat === 6, 'registros do patrimônio intactos (6) depois de usar o cemitério -> ' + nPat);
  const q = await ctxPat.newPage(); await q.goto('http://localhost:8765/patrimonio/app-campo/'); await q.waitForURL(/motivo=sem-acesso/);
  ok(true, 'usuário selemitério não entra no Patrimônio');
  const t = await b.newContext({ ...require('/opt/node22/lib/node_modules/playwright').devices['iPad (gen 7)'], locale: 'pt-BR' });
  const tp = await t.newPage(); await tp.goto('http://localhost:8765/');
  await tp.fill('#usuario', 'SELEMITERIO'); await tp.fill('#senha', '123456'); await tp.click('button[type=submit]');
  await tp.waitForURL('**/cemiterio/gestao/**'); await tp.goto(URL); await tp.waitForSelector('[data-ir]');
  await tp.screenshot({ path: S0 + '/prints/cemiterio/4-inicio-tablet.png' });
  ok(await tp.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'cemitério tablet: sem rolagem lateral');
  await t.close();
  const pequeno = await b.newContext({ viewport: { width: 360, height: 740 }, isMobile: true, hasTouch: true });
  const sp = await pequeno.newPage(); await sp.goto('http://localhost:8765/');
  await sp.fill('#usuario', 'patrimonio'); await sp.fill('#senha', '123456'); await sp.click('button[type=submit]');
  await sp.waitForURL('**/patrimonio/gestao/**'); await sp.goto('http://localhost:8765/patrimonio/app-campo/'); await sp.waitForSelector('[data-ir]');
  await sp.screenshot({ path: S0 + '/prints/patrimonio/celular-360.png' });
  ok(await sp.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'celular pequeno (360 px): cabeçalho sem rolagem lateral');
  await pequeno.close();
  ok(erros.length === 0, 'sem erros no console (os dois sistemas) ' + JSON.stringify(erros));
};
